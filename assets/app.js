  function go(view, push = true) {
    if (!VIEWS.includes(view)) view = "f1";
    document.body.dataset.view = view;
    VIEWS.forEach((v) => {
      const el = document.getElementById("view-" + v);
      if (el) el.classList.toggle("is-active", v === view);
    });
    document.querySelectorAll(".nav-item").forEach((b) => {
      const on = b.dataset.view === view;
      b.classList.toggle("is-active", on);
      if (on) b.setAttribute("aria-current", "page");
      else b.removeAttribute("aria-current");
    });
    if (push && location.hash !== "#" + view) history.replaceState(null, "", "#" + view);
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  function initShell() {
    $("#ticker").innerHTML = tickerItems() + tickerItems();
    const genEl = $("#generated");
    genEl.textContent = (() => { const p = cstParts(D.generatedAt); return p ? `${p.y}.${p.m}.${p.d} ${p.h}:${p.mi}` : "—"; })();
    const ageHours = (Date.now() - new Date(D.generatedAt).getTime()) / 3600000;
    if (Number.isFinite(ageHours) && ageHours > 36) {
      genEl.classList.add("is-stale");
      genEl.title = `快照已约 ${Math.floor(ageHours)} 小时未更新，数据可能过期`;
      genEl.insertAdjacentHTML("afterend", ' <span class="stale-mark" title="数据快照超过 36 小时">⚠</span>');
    }
    $("#sources").innerHTML = (D.sources || []).map((s) => `<a href="${esc(s.url)}" target="_blank" rel="noopener">${esc(s.name)}</a>`).join("");
    $("#clock").textContent = new Intl.DateTimeFormat("zh-CN", { timeZone: CST, hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: false }).format(new Date());

    document.querySelectorAll(".nav-item").forEach((b) => b.addEventListener("click", () => go(b.dataset.view)));
    window.addEventListener("hashchange", () => go(location.hash.replace("#", ""), false));
    go(location.hash.replace("#", "") || "f1", false);

    setInterval(() => {
      $("#clock").textContent = new Intl.DateTimeFormat("zh-CN", { timeZone: CST, hour: "2-digit", minute: "2-digit", second: "2-digit", hour12: false }).format(new Date());
      tickCountdowns();
    }, 1000);

    document.addEventListener("click", (e) => {
      const btn = e.target.closest("[data-filter]");
      if (!btn) return;
      const group = btn.dataset.group;
      state[group] = btn.dataset.filter;
      btn.parentElement.querySelectorAll(".filter-btn").forEach((b) => b.classList.toggle("is-active", b === btn));
      const list = document.getElementById(`${group}-match-list`);
      if (!list) return;
      list.querySelectorAll(".match-item").forEach((item) => {
        const s = item.dataset.status;
        const show = state[group] === "all" || (state[group] === "upcoming" ? s !== "已结束" : s === "已结束");
        item.style.display = show ? "" : "none";
      });
    });
  }

