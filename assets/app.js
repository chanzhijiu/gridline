        id: `kpl-${m.id}`, series: "kpl", view: "kpl", title: `${m.teamA || "TBD"} vs ${m.teamB || "TBD"}`,
        sub: `${m.stage || ""} · BO${m.bo || "5"}${m.location ? ` · ${m.location}` : ""}`,
